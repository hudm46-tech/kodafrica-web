-- database/schema.sql
SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

CREATE TABLE IF NOT EXISTS branches (
  branch_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_name VARCHAR(100) NOT NULL,
  location VARCHAR(200) NOT NULL,
  phone_number VARCHAR(30) NOT NULL,
  tin_number VARCHAR(50),
  license_number VARCHAR(100) NOT NULL,
  license_expiry_date DATE NOT NULL,
  license_pdf_path VARCHAR(255),
  is_active TINYINT(1) DEFAULT 1,
  is_synced TINYINT(1) DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS employees (
  employee_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT DEFAULT 0,
  full_name VARCHAR(150) NOT NULL,
  phone_number VARCHAR(30) NOT NULL UNIQUE,
  email VARCHAR(150),
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('ADMIN','MANAGER','CASHIER') NOT NULL DEFAULT 'CASHIER',
  employment_type ENUM('PERMANENT','CASUAL') NOT NULL DEFAULT 'PERMANENT',
  monthly_salary DECIMAL(12,2) DEFAULT 0,
  daily_rate DECIMAL(12,2) DEFAULT 0,
  hire_date DATETIME,
  is_active TINYINT(1) DEFAULT 1,
  nssf_number VARCHAR(50),
  notes TEXT,
  failed_login_count INT DEFAULT 0,
  last_failed_login DATETIME NULL,
  is_synced TINYINT(1) DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_phone (phone_number),
  INDEX idx_branch (branch_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS products (
  product_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT NOT NULL,
  name VARCHAR(200) NOT NULL,
  unit_of_measure VARCHAR(20) NOT NULL DEFAULT 'PCS',
  quantity INT NOT NULL DEFAULT 0,
  minimum_stock INT NOT NULL DEFAULT 5,
  purchase_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  selling_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  category VARCHAR(50),
  supplier VARCHAR(150),
  remarks TEXT,
  is_synced TINYINT(1) DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_branch_name (branch_id, name),
  INDEX idx_low_stock (branch_id, quantity, minimum_stock),
  CONSTRAINT fk_products_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS sales (
  sale_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT NOT NULL,
  employee_id INT NOT NULL,
  product_id INT NOT NULL,
  product_name VARCHAR(200) NOT NULL,
  quantity_sold INT NOT NULL,
  purchase_price_at_sale DECIMAL(12,2) NOT NULL,
  selling_price_at_sale DECIMAL(12,2) NOT NULL,
  discount DECIMAL(12,2) DEFAULT 0,
  total_amount DECIMAL(12,2) NOT NULL,
  payment_method VARCHAR(30) NOT NULL,
  payment_reference VARCHAR(100),
  customer_phone VARCHAR(30),
  customer_name VARCHAR(150),
  credit_due_date DATETIME NULL,
  is_paid TINYINT(1) DEFAULT 1,
  receipt_type ENUM('NORMAL','EFD') DEFAULT 'NORMAL',
  efd_receipt_number VARCHAR(50),
  vfd_status VARCHAR(20) DEFAULT 'PENDING',
  sale_date DATETIME DEFAULT CURRENT_TIMESTAMP,
  notes TEXT,
  is_synced TINYINT(1) DEFAULT 0,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_sale_date (sale_date),
  INDEX idx_branch_date (branch_id, sale_date),
  INDEX idx_unpaid (is_paid, credit_due_date),
  CONSTRAINT fk_sales_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_sales_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
  CONSTRAINT fk_sales_product FOREIGN KEY (product_id) REFERENCES products(product_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS expenses (
  expense_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT NOT NULL,
  employee_id INT DEFAULT 0,
  category VARCHAR(40) NOT NULL,
  description VARCHAR(255) NOT NULL,
  amount DECIMAL(12,2) NOT NULL,
  receipt_image_path VARCHAR(255),
  receipt_pdf_path VARCHAR(255),
  expense_date DATETIME NOT NULL,
  notes TEXT,
  is_synced TINYINT(1) DEFAULT 0,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_branch_date (branch_id, expense_date),
  INDEX idx_category (category),
  CONSTRAINT fk_expenses_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS utility_bills (
  bill_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT NOT NULL,
  bill_type VARCHAR(30) NOT NULL,
  bill_month VARCHAR(20) NOT NULL,
  bill_year INT NOT NULL,
  meter_number VARCHAR(50),
  provider VARCHAR(100),
  amount_due DECIMAL(12,2) NOT NULL,
  amount_paid DECIMAL(12,2) DEFAULT 0,
  is_paid TINYINT(1) DEFAULT 0,
  due_date DATETIME NULL,
  paid_date DATETIME NULL,
  receipt_image_path VARCHAR(255),
  receipt_pdf_path VARCHAR(255),
  reference_number VARCHAR(100),
  notes TEXT,
  is_synced TINYINT(1) DEFAULT 0,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_branch_year (branch_id, bill_year),
  INDEX idx_unpaid (is_paid, due_date),
  CONSTRAINT fk_bills_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS salary_payments (
  payment_id INT AUTO_INCREMENT PRIMARY KEY,
  employee_id INT NOT NULL,
  branch_id INT NOT NULL,
  payment_type ENUM('SALARY','POSHO','OVERTIME','ADVANCE','BONUS','NSSF') NOT NULL,
  period_month VARCHAR(20) NOT NULL,
  period_year INT NOT NULL,
  days_worked INT DEFAULT 0,
  daily_rate DECIMAL(12,2) DEFAULT 0,
  base_amount DECIMAL(12,2) DEFAULT 0,
  overtime_hours DECIMAL(8,2) DEFAULT 0,
  overtime_rate DECIMAL(12,2) DEFAULT 0,
  overtime_amount DECIMAL(12,2) DEFAULT 0,
  bonus DECIMAL(12,2) DEFAULT 0,
  deductions DECIMAL(12,2) DEFAULT 0,
  amount_paid DECIMAL(12,2) NOT NULL,
  payment_method VARCHAR(30) NOT NULL,
  payment_reference VARCHAR(100),
  payment_date DATETIME DEFAULT CURRENT_TIMESTAMP,
  receipt_image_path VARCHAR(255),
  receipt_pdf_path VARCHAR(255),
  notes TEXT,
  is_synced TINYINT(1) DEFAULT 0,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_period (branch_id, period_year, period_month),
  INDEX idx_employee (employee_id),
  CONSTRAINT fk_salary_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
  CONSTRAINT fk_salary_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS app_settings (
  id INT PRIMARY KEY DEFAULT 1,
  business_name VARCHAR(150),
  business_tagline VARCHAR(200),
  business_logo_path VARCHAR(255),
  business_address VARCHAR(255),
  business_phone VARCHAR(30),
  business_email VARCHAR(150),
  business_tin VARCHAR(50),
  business_vrn VARCHAR(50),
  language VARCHAR(5) DEFAULT 'en',
  theme VARCHAR(10) DEFAULT 'light',
  receipt_mode ENUM('NORMAL_ONLY','EFD_ONLY','BOTH') DEFAULT 'BOTH',
  cash_enabled TINYINT(1) DEFAULT 1,
  mpesa_enabled TINYINT(1) DEFAULT 1,
  tigo_pesa_enabled TINYINT(1) DEFAULT 1,
  airtel_money_enabled TINYINT(1) DEFAULT 1,
  halo_pesa_enabled TINYINT(1) DEFAULT 1,
  credit_enabled TINYINT(1) DEFAULT 1,
  vfd_enabled TINYINT(1) DEFAULT 0,
  vfd_device_serial VARCHAR(100),
  vfd_tin VARCHAR(50),
  default_minimum_stock INT DEFAULT 5,
  low_stock_alerts_enabled TINYINT(1) DEFAULT 1,
  license_reminder_days INT DEFAULT 30,
  license_alerts_enabled TINYINT(1) DEFAULT 1,
  auto_sync_enabled TINYINT(1) DEFAULT 0,
  last_sync_time DATETIME NULL,
  database_encryption_enabled TINYINT(1) DEFAULT 0,
  password_hashing_enabled TINYINT(1) DEFAULT 1,
  local_backup_enabled TINYINT(1) DEFAULT 1,
  local_backup_time VARCHAR(10) DEFAULT '22:00',
  cloud_backup_enabled TINYINT(1) DEFAULT 1,
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tax_settings (
  id INT PRIMARY KEY DEFAULT 1,
  entity_type ENUM('SOLE_PROPRIETOR','LIMITED_COMPANY') DEFAULT 'SOLE_PROPRIETOR',
  presumptive_enabled TINYINT(1) DEFAULT 1,
  presumptive_threshold1 DECIMAL(15,2) DEFAULT 4000000,
  presumptive_rate1 DECIMAL(5,2) DEFAULT 0,
  presumptive_threshold2 DECIMAL(15,2) DEFAULT 7000000,
  presumptive_rate2 DECIMAL(5,2) DEFAULT 3,
  presumptive_threshold3 DECIMAL(15,2) DEFAULT 11000000,
  presumptive_fixed_fee3 DECIMAL(15,2) DEFAULT 90000,
  presumptive_rate3 DECIMAL(5,2) DEFAULT 3,
  presumptive_threshold4 DECIMAL(15,2) DEFAULT 200000000,
  presumptive_fixed_fee4 DECIMAL(15,2) DEFAULT 250000,
  presumptive_rate4 DECIMAL(5,2) DEFAULT 4,
  corporate_enabled TINYINT(1) DEFAULT 1,
  corporate_rate DECIMAL(5,2) DEFAULT 30,
  vat_enabled TINYINT(1) DEFAULT 1,
  vat_rate DECIMAL(5,2) DEFAULT 18,
  vat_registration_threshold DECIMAL(15,2) DEFAULT 100000000,
  vat_remittance_day INT DEFAULT 20,
  updated_by VARCHAR(150),
  last_updated DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tax_report_history (
  report_id INT AUTO_INCREMENT PRIMARY KEY,
  report_year INT NOT NULL,
  report_month INT DEFAULT 0,
  branch_id INT DEFAULT 0,
  entity_type VARCHAR(30),
  regime_used VARCHAR(30),
  total_sales DECIMAL(15,2) DEFAULT 0,
  total_expenses DECIMAL(15,2) DEFAULT 0,
  cost_of_goods_sold DECIMAL(15,2) DEFAULT 0,
  gross_profit DECIMAL(15,2) DEFAULT 0,
  net_profit DECIMAL(15,2) DEFAULT 0,
  annual_turnover DECIMAL(15,2) DEFAULT 0,
  estimated_tax DECIMAL(15,2) DEFAULT 0,
  vat_amount DECIMAL(15,2) DEFAULT 0,
  vat_required TINYINT(1) DEFAULT 0,
  corporate_rate_used DECIMAL(5,2),
  presumptive_rate_used DECIMAL(5,2),
  vat_rate_used DECIMAL(5,2),
  presumptive_bracket_used DECIMAL(5,2),
  pdf_path VARCHAR(255),
  excel_path VARCHAR(255),
  generated_date DATETIME DEFAULT CURRENT_TIMESTAMP,
  generated_by VARCHAR(150),
  notes TEXT,
  is_synced TINYINT(1) DEFAULT 0
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS password_resets (
  id INT AUTO_INCREMENT PRIMARY KEY,
  employee_id INT NOT NULL,
  token_hash VARCHAR(255) NOT NULL,
  expires_at DATETIME NOT NULL,
  used_at DATETIME NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_pr_emp FOREIGN KEY (employee_id) REFERENCES employees(employee_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  employee_id INT NULL,
  action VARCHAR(50) NOT NULL,
  entity VARCHAR(50),
  entity_id INT,
  details TEXT,
  ip_address VARCHAR(45),
  user_agent VARCHAR(255),
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_created (created_at)
) ENGINE=InnoDB;

SET FOREIGN_KEY_CHECKS = 1;
