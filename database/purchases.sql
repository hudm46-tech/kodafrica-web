-- Purchases (stock purchase records). Run once on your database.
CREATE TABLE IF NOT EXISTS purchases (
  purchase_id INT AUTO_INCREMENT PRIMARY KEY,
  branch_id INT NOT NULL,
  product_id INT NULL,
  product_name VARCHAR(200) NOT NULL,
  unit_of_measure VARCHAR(20) NOT NULL DEFAULT 'PCS',
  supplier_name VARCHAR(150) NOT NULL,
  quantity INT NOT NULL,
  purchase_price DECIMAL(12,2) NOT NULL,
  selling_price DECIMAL(12,2) NOT NULL,
  total_cost DECIMAL(14,2) NOT NULL,
  prev_purchase_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  prev_selling_price DECIMAL(12,2) NOT NULL DEFAULT 0,
  receipt_number VARCHAR(60),
  notes VARCHAR(255),
  purchase_date DATE NOT NULL,
  status ENUM('ACTIVE','VOIDED') NOT NULL DEFAULT 'ACTIVE',
  void_reason VARCHAR(255),
  voided_at DATETIME NULL,
  voided_by INT NULL,
  created_by INT NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_purchase_branch_date (branch_id, purchase_date),
  INDEX idx_purchase_product (product_id),
  INDEX idx_purchase_supplier (supplier_name),
  CONSTRAINT fk_purchases_branch FOREIGN KEY (branch_id) REFERENCES branches(branch_id),
  CONSTRAINT fk_purchases_product FOREIGN KEY (product_id) REFERENCES products(product_id) ON DELETE SET NULL
) ENGINE=InnoDB;
